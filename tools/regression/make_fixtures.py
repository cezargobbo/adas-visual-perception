SAMPLE_STRIDE = 32


# --------------------------------------------------------------------------- helpers
def hash_image(h: int, w: int, seed: int) -> np.ndarray:
    """Pseudo-noise BGR uint8 image (h, w, 3) from an integer hash (lowbias32).

    idx = (y * w + x) * 3 + c;  v = lowbias32(idx + seed * 0x9E3779B9)  (all uint32, wrapping);
    pixel = v >> 24.  Trivial to reproduce in C++ with uint32_t arithmetic.
    """
    idx = np.arange(h * w * 3, dtype=np.uint32)
    x = idx + np.uint32((seed * 0x9E3779B9) & 0xFFFFFFFF)
    x ^= x >> np.uint32(16)
    x *= np.uint32(0x7FEB352D)
    x ^= x >> np.uint32(15)
    x *= np.uint32(0x846CA68B)
    x ^= x >> np.uint32(16)
    return (x >> np.uint32(24)).astype(np.uint8).reshape(h, w, 3)


def bits_checksums(a: np.ndarray) -> dict:
    """Order-sensitive checksums over the float32 bit patterns (C order), as hex strings.

    bits_sum  = sum(word)               mod 2^64
    bits_wsum = sum((i + 1) * word)     mod 2^64     (i = flat index, word = uint32 bit pattern)
    """
    w = np.ascontiguousarray(a, dtype=np.float32).view(np.uint32).ravel().astype(np.uint64)
    i = np.arange(1, w.size + 1, dtype=np.uint64)
    return {"bits_sum": f"{int(w.sum(dtype=np.uint64)):016x}",
            "bits_wsum": f"{int((w * i).sum(dtype=np.uint64)):016x}"}


def save_npy(out: Path, name: str, arr: np.ndarray) -> None:
    assert arr.dtype in (np.float32, np.int32, np.int64, np.uint8), (name, arr.dtype)
    np.save(out / name, np.ascontiguousarray(arr))


def save_json(out: Path, name: str, obj) -> None:
    (out / name).write_text(json.dumps(obj, indent=1) + "\n")


def f32_list(a) -> list:
    return [float(v) for v in np.asarray(a).ravel()]


# --------------------------------------------------------------------------- letterbox
def make_letterbox(out: Path) -> None:
    # Big cases: input regenerated from hash_image, expected = checksums + strided sample.
    for (w, h) in [(1920, 1080), (1280, 720), (854, 474)]:
        for imgsz in (960, 1280):
            seed = 1000 + w % 1000 + imgsz % 100
            img = hash_image(h, w, seed)
            t, r, (left, top) = letterbox(img, imgsz)
            name = f"letterbox_{w}x{h}_s{imgsz}"
            save_npy(out, f"{name}_samples.npy", t[0, :, ::SAMPLE_STRIDE, ::SAMPLE_STRIDE])
            save_json(out, f"{name}.json", {
                "input": {"kind": "hash_image", "width": w, "height": h, "seed": seed},
                "imgsz": imgsz, "ratio": r, "pad": [left, top], "shape": list(t.shape),
                "sample_stride": SAMPLE_STRIDE, **bits_checksums(t)})
    # Tiny cases stored in full. Chosen to cover: upscale, downscale, odd padding (+-0.1 rounding),
    # no resize needed, no padding.
    for k, (w, h, imgsz) in enumerate([(160, 90, 128), (101, 57, 64), (100, 51, 64), (96, 96, 96), (51, 100, 64)]):
        img = np.random.default_rng(77 + k).integers(0, 256, (h, w, 3), dtype=np.uint8)
        t, r, (left, top) = letterbox(img, imgsz)
        name = f"letterbox_tiny{k}"
        save_npy(out, f"{name}_input.npy", img)
        save_npy(out, f"{name}_expected.npy", t)
        save_json(out, f"{name}.json", {"width": w, "height": h, "imgsz": imgsz, "ratio": r,
                                        "pad": [left, top], "shape": list(t.shape)})


# --------------------------------------------------------------------------- seg pre
MEAN = torch.tensor([0.485, 0.456, 0.406]).view(1, 3, 1, 1)
STD = torch.tensor([0.229, 0.224, 0.225]).view(1, 3, 1, 1)


def segformer_pre(frame_bgr: np.ndarray, w: int, h: int) -> np.ndarray:
    """Segmenter.__call__ preprocessing, fp32, CPU (same ops, same order)."""
    x = torch.from_numpy(frame_bgr)
    x = x[..., [2, 1, 0]].permute(2, 0, 1).unsqueeze(0).float() / 255.0
    x = F.interpolate(x, size=(h, w), mode="bilinear", align_corners=False)
    x = (x - MEAN) / STD
    return x.numpy()


