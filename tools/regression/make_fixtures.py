#!/usr/bin/env python3
"""Generate the deterministic test fixtures consumed by the C++ unit tests.

Everything is synthetic (fixed seeds, no video frames) and the whole directory must stay
below 2 MB. Usage:  python tools/regression/make_fixtures.py --out tests/fixtures

Files are .npy (float32 / int32 / int64 / uint8, C order) or small .json files. Where a
float64 value matters (Kalman state) the data is stored as JSON with full-precision
doubles. See tests/fixtures/README.md for the meaning of every file.

Large images are never stored: they are re-generated by the C++ test from an integer hash
(see hash_image below, reproducible with uint32 arithmetic) and the expected result is
stored as exact checksums plus a strided sample of the tensor. Small cases are stored in
full (input and expected output).
"""
